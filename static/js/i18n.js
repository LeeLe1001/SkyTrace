function translateAirline(name) {
  if (!name) return '';
  const entry = AIRLINE_NAMES[name];
  if (!entry) return name;
  return entry[currentLang] || name;
}

// ========== i18n 引擎 ==========
let currentLang = localStorage.getItem('skytrace-lang') || 'zh';

function t(key, ...args) {
  const str = (I18N[currentLang] && I18N[currentLang][key]) || (I18N.zh[key]) || key;
  if (args.length === 0) return str;
  return str.replace(/\{(\d+)\}/g, (_, i) => args[parseInt(i)] ?? '');
}

function setLanguage(lang) {
  if (!I18N[lang]) return;
  currentLang = lang;
  localStorage.setItem('skytrace-lang', lang);
  try { applyI18n(); } catch (e) { console.error('[i18n] applyI18n failed:', e); }
  // 刷新动态内容
  try { if (typeof loadFlights === 'function') loadFlights(); } catch (e) { console.error('[i18n] loadFlights failed:', e); }
  try { if (typeof loadStats === 'function') loadStats(); } catch (e) { console.error('[i18n] loadStats failed:', e); }
}

// BCP 47 语言标签映射
const LANG_TAG = { zh: 'zh-CN', en: 'en-US', ja: 'ja-JP', ko: 'ko-KR', es: 'es-ES' };

function applyI18n() {
  // 更新 <html lang> 属性, 影响浏览器原生控件语言
  const langTag = LANG_TAG[currentLang] || 'zh-CN';
  document.documentElement.lang = langTag;

  // 更新所有 date input 的 lang 属性
  document.querySelectorAll('input[type="date"]').forEach(el => {
    el.lang = langTag;
  });

  // 页面标题
  document.title = t('appTitle');

  // 遍历所有 data-i18n 属性的元素
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const val = t(key);
    if (el.tagName === 'INPUT' && el.type !== 'hidden') {
      // placeholder
    } else if (el.tagName === 'OPTION') {
      el.textContent = val;
    } else {
      el.innerHTML = val;
    }
  });

  // data-i18n-placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
  });

  // data-i18n-title
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.title = t(el.getAttribute('data-i18n-title'));
  });

  // 更新语言选择器高亮
  document.querySelectorAll('.lang-option').forEach(el => {
    el.classList.toggle('active', el.dataset.lang === currentLang);
  });
}
